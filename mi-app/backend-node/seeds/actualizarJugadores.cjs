const actualizarJugadores = async () => {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('✅ Conectado a MongoDB Atlas\n');

    let actualizados = 0;
    let noEncontrados = [];
    const total = datosJugadores.length;
    const startTime = Date.now();

    for (let i = 0; i < datosJugadores.length; i++) {
      const datos = datosJugadores[i];

      // Buscar el equipo por nombre para usarlo como segundo filtro
      const equipo = await Equipo.findOne({ nombre: datos.equipo });

      const filtro = equipo
        ? { nombre: datos.nombre, equipo: equipo._id }
        : { nombre: datos.nombre };

      const resultado = await Jugador.updateOne(
        filtro,
        { $set: { posicion: datos.posicion, fechaNacimiento: datos.fechaNacimiento } }
      );

      if (resultado.matchedCount === 0) {
        noEncontrados.push(datos.nombre);
      } else {
        actualizados++;
      }

      // Barra de progreso
      const progreso = i + 1;
      const porcentaje = Math.floor((progreso / total) * 100);
      const barLength = 30;
      const filled = Math.floor((progreso / total) * barLength);
      const bar = '█'.repeat(filled) + '░'.repeat(barLength - filled);
      const elapsed = ((Date.now() - startTime) / 1000).toFixed(1);
      process.stdout.write(`\r[${bar}] ${porcentaje}% | ${progreso}/${total} jugadores | ${elapsed}s`);
    }

    const totalTime = ((Date.now() - startTime) / 1000).toFixed(1);
    console.log(`\n\n✅ Jugadores actualizados: ${actualizados}`);
    if (noEncontrados.length > 0) {
      console.log(`\n⚠️  Jugadores no encontrados en BD (${noEncontrados.length}):`);
      noEncontrados.forEach(n => console.log(`   - ${n}`));
    }
    console.log(`\n⏱️  Tiempo total: ${totalTime}s`);
    console.log('🎉 Actualización completada');
    process.exit(0);
  } catch (error) {
    console.error('❌ Error durante la actualización:', error);
    process.exit(1);
  }
};

actualizarJugadores();